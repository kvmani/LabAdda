"""Text of the generated systemd unit and nginx files for one site (standard library only).

operations.py validates the site description first; everything here only formats it.
"""

from __future__ import annotations

CONTENT_SECURITY_POLICY = (
    "default-src 'self'; img-src 'self' data: blob:; connect-src 'self'; "
    "script-src 'self' 'unsafe-inline'; style-src 'self'; frame-ancestors 'none'"
)


def _system_unit(site: dict) -> str:
    root = site["root"]
    return f"""# Generated by operations.py; install as labadda-{site["instance"]}.service
[Unit]
Description=LabAdda ({site["instance"]})
After=network-online.target
Wants=network-online.target
StartLimitIntervalSec=60
StartLimitBurst=5
[Service]
Type=simple
User={site["user"]}
Group={site["group"]}
EnvironmentFile={site["env_file"]}
WorkingDirectory={root}/current/backend
ExecStart={root}/current/venv/bin/python -I -m labadda.cli serve --host 127.0.0.1 --port {site["port"]}
Restart=on-failure
RestartSec=5
TimeoutStopSec=60
KillMode=control-group
UMask=0077
NoNewPrivileges=true
PrivateTmp=true
PrivateDevices=true
ProtectSystem=strict
ProtectHome=true
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true
RestrictSUIDSGID=true
RestrictRealtime=true
LockPersonality=true
RestrictAddressFamilies=AF_UNIX AF_INET AF_INET6
ReadWritePaths={root}/assets
[Install]
WantedBy=multi-user.target
"""


def _user_unit(site: dict) -> str:
    """The same service in the operator's systemd user manager. User and Group are implicit, and the
    namespace-based sandboxing of the system unit is left out: Ubuntu 24.04 restricts the
    unprivileged user namespaces it needs, and a unit that cannot start protects nothing."""
    root = site["root"]
    return f"""# Generated by operations.py; systemd USER unit labadda-{site["instance"]}.service
[Unit]
Description=LabAdda ({site["instance"]})
StartLimitIntervalSec=60
StartLimitBurst=5
[Service]
Type=simple
EnvironmentFile={site["env_file"]}
WorkingDirectory={root}/current/backend
ExecStart={root}/current/venv/bin/python -I -m labadda.cli serve --host 127.0.0.1 --port {site["port"]}
Restart=on-failure
RestartSec=5
TimeoutStopSec=60
KillMode=control-group
UMask=0077
NoNewPrivileges=true
[Install]
WantedBy=default.target
"""


def unit_file(site: dict) -> str:
    return _user_unit(site) if site["service_scope"] == "user" else _system_unit(site)


def nginx_files(site: dict) -> dict[str, str]:
    """`nginx.conf` goes to conf.d; a shared site also gets `locations.conf` for its server block."""
    if site["web_access"] == "shared-http":
        return _shared_site(site)
    if site["web_access"] == "dedicated-http":
        return {"nginx.conf": _plain_http_site(site)}
    return {"nginx.conf": _dedicated_site(site)}


def _upgrade_variable(site: dict) -> str:
    return f"$labadda_{site['instance'].replace('-', '_')}_upgrade"


def _proxy_lines(site: dict) -> str:
    return f"""        proxy_pass http://127.0.0.1:{site["port"]};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection {_upgrade_variable(site)};
        proxy_set_header Host $http_host;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_set_header X-Forwarded-For $remote_addr;
        proxy_set_header X-Request-ID $request_id;
        proxy_read_timeout 1h;"""


def _dedicated_site(site: dict) -> str:
    """Own HTTPS server block. A server-level gate covers shell, APIs, downloads, static files and
    new sockets; existing sockets end when the service stops before backup or migration."""
    root, base = site["root"], site["base_path"]
    return f"""# Generated by operations.py; included inside nginx's http context.
# The operator must create {root}/traffic (0755) before nginx -t.
map $http_upgrade {_upgrade_variable(site)} {{ default upgrade; '' close; }}
# A co-hosted app may own the plain-HTTP default site; without this block a typed http:// address
# would reach that other app instead of LabAdda.
server {{
    listen 80;
    server_name {site["server_name"]};
    return 301 https://$host$request_uri;
}}
server {{
    listen 443 ssl;
    server_name {site["server_name"]};
    ssl_certificate {site["tls_certificate"]};
    ssl_certificate_key {site["tls_key"]};
    ssl_protocols TLSv1.2 TLSv1.3;
    client_max_body_size 25m;
    if (-f {root}/traffic/maintenance) {{ return 503; }}
    add_header X-Content-Type-Options nosniff always;
    add_header Referrer-Policy same-origin always;
    add_header Content-Security-Policy "{CONTENT_SECURITY_POLICY}" always;
    location {base}/assets/ {{
        alias {root}/current/frontend/dist/assets/;
        add_header Cache-Control "public, max-age=31536000, immutable";
    }}
    location {base}/ {{
{_proxy_lines(site)}
    }}
}}
"""


def _plain_http_site(site: dict) -> str:
    """Own plain-HTTP server block for a server reached by its IP address, without a certificate.

    It matches its own address only, so Ubuntu's stock default site (or any other) keeps every
    other name; nothing else on the server is edited."""
    root, base = site["root"], site["base_path"]
    bare = (
        f"""    location = {base} {{
        return 301 {base}/;
    }}
"""
        if base
        else ""
    )
    return f"""# Generated by operations.py; included inside nginx's http context.
# The operator must create {root}/traffic (0755) before nginx -t.
map $http_upgrade {_upgrade_variable(site)} {{ default upgrade; '' close; }}
server {{
    listen 80;
    server_name {site["server_name"]};
    client_max_body_size 25m;
    if (-f {root}/traffic/maintenance) {{ return 503; }}
    add_header X-Content-Type-Options nosniff always;
    add_header Referrer-Policy same-origin always;
    add_header Content-Security-Policy "{CONTENT_SECURITY_POLICY}" always;
{bare}    location {base}/assets/ {{
        alias {root}/current/frontend/dist/assets/;
        add_header Cache-Control "public, max-age=31536000, immutable";
    }}
    location {base}/ {{
{_proxy_lines(site)}
    }}
}}
"""


def _shared_site(site: dict) -> dict[str, str]:
    """Locations for another application's server block, plus the http-context map they need.

    The other application owns the server block, so every LabAdda setting (upload size, headers,
    maintenance gate) is repeated per location and nothing outside the prefix is touched."""
    root, base = site["root"], site["base_path"]
    gate = f"if (-f {root}/traffic/maintenance) {{ return 503; }}"
    headers = (
        "add_header X-Content-Type-Options nosniff always;\n"
        "        add_header Referrer-Policy same-origin always;\n"
        f'        add_header Content-Security-Policy "{CONTENT_SECURITY_POLICY}" always;'
    )
    http_context = f"""# Generated by operations.py; included inside nginx's http context.
map $http_upgrade {_upgrade_variable(site)} {{ default upgrade; '' close; }}
"""
    locations = f"""# Generated by operations.py. Included INSIDE the shared site's server block by the line
# "include <this file>;" that the LabAdda installer adds. Only {base} is served from here.
    location = {base} {{
        return 301 {base}/;
    }}
    location ^~ {base}/assets/ {{
        {gate}
        alias {root}/current/frontend/dist/assets/;
        add_header Cache-Control "public, max-age=31536000, immutable";
        add_header X-Content-Type-Options nosniff always;
    }}
    location ^~ {base}/ {{
        {gate}
        client_max_body_size 25m;
        {headers}
{_proxy_lines(site)}
    }}
"""
    return {"nginx.conf": http_context, "locations.conf": locations}
